import json
from flask import Blueprint, request, jsonify, session, g, Response, stream_with_context
from app.routes.auth import login_required
from app.services.chatbot_service import (
    ChatbotServiceError,
    get_chatbot_response,
    stream_chatbot_tokens,
)
from app.services.voice_assistant_service import process_voice_assistant_command
from app.database.connection import get_db

chatbot_bp = Blueprint('chatbot', __name__, url_prefix='/api/chatbot')


@chatbot_bp.route('/stream', methods=['POST'])
@login_required
def stream():
    """
    Progressive real-time streaming endpoint for the AI Chatbot.
    Streams individual tokens as generated by local Ollama via SSE.
    """
    data = request.get_json() or {}
    user_message = data.get('message', '').strip()
    language = data.get('language', 'en')
    conversation = data.get('conversation', [])
    user_id = session.get('user_id')

    if not user_message:
        return jsonify({'error': 'Message cannot be empty'}), 400

    def event_stream():
        full_text_chunks = []
        try:
            for token in stream_chatbot_tokens(
                user_message=user_message,
                language=language,
                conversation=conversation if isinstance(conversation, list) else [],
            ):
                full_text_chunks.append(token)
                yield f"data: {json.dumps({'token': token})}\n\n"
        except Exception as exc:
            yield f"data: {json.dumps({'error': str(exc)})}\n\n"
            return

        full_text = "".join(full_text_chunks).strip()
        if user_id and full_text:
            try:
                with get_db() as conn:
                    cursor = conn.cursor()
                    cursor.execute(
                        "INSERT INTO chat_history (user_id, user_message, bot_response) VALUES (%s, %s, %s)",
                        (user_id, user_message, full_text)
                    )
                    cursor.close()
            except Exception:
                pass

        yield f"data: {json.dumps({'done': True, 'full_response': full_text})}\n\n"

    return Response(
        stream_with_context(event_stream()),
        mimetype='text/event-stream',
        headers={
            'Cache-Control': 'no-cache',
            'X-Accel-Buffering': 'no',
        }
    )


@chatbot_bp.route('/chat', methods=['POST'])
@login_required
def chat():
    """
    Normal Question-Answer Chatbot.
    Answers user questions normally via the local LLM / Ollama service.
    Keeps conversation strictly normal without routing to the hospital agent.
    """
    data = request.get_json() or {}
    user_message = data.get('message', '').strip()
    current_page = data.get('current_page', '')
    language = data.get('language', 'en')
    conversation = data.get('conversation', [])
    user_id = session.get('user_id')

    if not user_message:
        return jsonify({'error': 'Message cannot be empty'}), 400

    if not isinstance(conversation, list):
        return jsonify({'error': 'Conversation history must be a list.'}), 400

    try:
        result = get_chatbot_response(
            user_message,
            current_page=current_page,
            language=language,
            conversation=conversation,
        )
    except ChatbotServiceError as exc:
        return jsonify({'error': str(exc)}), 503

    result.pop('disclaimer', None)

    # Save to chat_history table
    try:
        with get_db() as conn:
            cursor = conn.cursor()
            cursor.execute(
                "INSERT INTO chat_history (user_id, user_message, bot_response) VALUES (%s, %s, %s)",
                (user_id, user_message, result.get('response', ''))
            )
            cursor.close()
    except Exception:
        pass

    return jsonify(result)


@chatbot_bp.route('/voice-command', methods=['POST'])
@login_required
def voice_command():
    """
    Standard voice assistant command handler for platform navigation and speech commands.
    """
    data = request.get_json() or {}
    user_message = data.get('message', '').strip()
    current_page = data.get('current_page', '')
    language = data.get('language', 'en')
    conversation = data.get('conversation', [])
    user_location = data.get('user_location')
    user_id = session.get('user_id')
    user_info = getattr(g, 'user', None) or {}
    if not user_info.get('id') and user_id:
        user_info['id'] = user_id

    if not user_message:
        return jsonify({'error': 'Speech input cannot be empty'}), 400

    result = process_voice_assistant_command(
        message=user_message,
        current_page=current_page,
        language=language,
        user_location=user_location,
        user_info=user_info,
        conversation=conversation,
        pending_action=data.get('pending_action')
    )

    return jsonify(result)
